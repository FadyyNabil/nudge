namespace Marketplace.Services;

/// <summary>
/// Saves and deletes uploaded portfolio files.
/// Files are stored OUTSIDE wwwroot, so nobody can open them by guessing a URL.
/// They are only served by the Portfolio/File page, which checks permissions first.
/// </summary>
public class PortfolioStorage
{
    public const long MaxBytes = 5 * 1024 * 1024;   // 5 MB per file

    // Allowed types. The file's first bytes ("magic bytes") must match too,
    // so renaming a .exe to .png does not work.
    private static readonly Dictionary<string, (string Mime, byte[] Magic)> Allowed = new()
    {
        [".pdf"] = ("application/pdf", new byte[] { 0x25, 0x50, 0x44, 0x46 }),
        [".png"] = ("image/png", new byte[] { 0x89, 0x50, 0x4E, 0x47 }),
        [".jpg"] = ("image/jpeg", new byte[] { 0xFF, 0xD8, 0xFF }),
        [".jpeg"] = ("image/jpeg", new byte[] { 0xFF, 0xD8, 0xFF }),
        [".zip"] = ("application/zip", new byte[] { 0x50, 0x4B, 0x03, 0x04 }),
    };

    private readonly string _root;

    public PortfolioStorage(IConfiguration config, IWebHostEnvironment env)
    {
        var path = config["Uploads:Path"] ?? "App_Data/uploads";
        _root = Path.IsPathRooted(path) ? path : Path.Combine(env.ContentRootPath, path);
        Directory.CreateDirectory(_root);
    }

    /// <summary>Returns null if the file is fine, otherwise an error message.</summary>
    public async Task<string?> ValidateAsync(IFormFile file)
    {
        if (file.Length == 0) return "The file is empty.";
        if (file.Length > MaxBytes) return "The file is larger than 5 MB.";
        var ext = Path.GetExtension(file.FileName).ToLowerInvariant();
        if (!Allowed.TryGetValue(ext, out var rule)) return "Allowed files: PDF, PNG, JPG or ZIP.";

        var head = new byte[rule.Magic.Length];
        await using var s = file.OpenReadStream();
        var read = await s.ReadAsync(head.AsMemory(0, head.Length));
        return read == head.Length && head.SequenceEqual(rule.Magic) ? null : "The file content does not match its type.";
    }

    /// <summary>The stored MIME type for an allowed file name, or null when its extension is not allowed.</summary>
    public string? MimeFor(string fileName)
    {
        var ext = Path.GetExtension(fileName).ToLowerInvariant();
        return Allowed.TryGetValue(ext, out var rule) ? rule.Mime : null;
    }

    /// <summary>Saves under a random name. Call ValidateAsync first.</summary>
    public async Task<(string StoredName, string ContentType)> SaveAsync(IFormFile file)
    {
        var ext = Path.GetExtension(file.FileName).ToLowerInvariant();
        var stored = Guid.NewGuid().ToString("N") + ext;
        await using var target = File.Create(Path.Combine(_root, stored));
        await file.CopyToAsync(target);
        return (stored, Allowed[ext].Mime);
    }

    public string? GetPath(string storedName)
    {
        // Stored names are generated by us, but never trust a value that goes into a file path.
        var name = Path.GetFileName(storedName);
        var full = Path.Combine(_root, name);
        return File.Exists(full) ? full : null;
    }

    public void Delete(string? storedName)
    {
        if (string.IsNullOrEmpty(storedName)) return;
        var path = GetPath(storedName);
        if (path is not null) File.Delete(path);
    }
}
